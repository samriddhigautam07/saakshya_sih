import { createFileRoute, useNavigate } from "@tanstack/react-router";
import { useState } from "react";
import { toast } from "sonner";
import { Printer } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { findingsFor, setFindingStatus, useStore } from "@/lib/store";
import { overallStatus } from "@/lib/validation/engine";
import { FINDING_STATUSES, type Finding, type FindingStatus } from "@/lib/domain/types";
import { Empty, Loading, PageHeader, Panel, StatusBadge, fmtDate, fmtDateTime } from "@/components/vw/ui";

export const Route = createFileRoute("/review")({
  validateSearch: (s: Record<string, unknown>): { app?: string | undefined } => ({ app: typeof s["app"] === "string" ? s["app"] : undefined }),
  head: () => ({
    meta: [
      { title: "Results & Review — VerifyWise AI" },
      { name: "description", content: "Application validation report with findings, evidence, recommended actions and audit history." },
      { property: "og:title", content: "Results & Review — VerifyWise AI" },
      { property: "og:description", content: "Validation report with findings, evidence and reviewer audit history." },
    ],
  }),
  component: ReviewPage,
});

function ReviewPage() {
  const s = useStore();
  const { app } = Route.useSearch();
  const nav = useNavigate({ from: "/review" });
  if (!s) return <Loading />;
  const a = s.applications.find((x) => x.id === app) ?? null;
  const findings = a ? findingsFor(s, a) : [];

  return (
    <div>
      <PageHeader title="Results & Review" description="Validation report generated by deterministic rules. Reviewers decide outcomes; the system only flags."
        actions={a && <Button variant="outline" onClick={() => window.print()}><Printer className="h-4 w-4" />Print report</Button>} />
      <select aria-label="Application" className="mb-6 h-9 w-full max-w-md rounded-md border border-input bg-background px-3 text-sm" value={app ?? ""}
        onChange={(e) => nav({ search: { app: e.target.value || undefined } })}>
        <option value="">Select an application…</option>
        {s.applications.map((x) => <option key={x.id} value={x.id}>{x.id} — {x.institutionName || "Unnamed"}</option>)}
      </select>
      {!a ? <Empty title="Choose an application to generate its validation report." /> : (
        <div className="space-y-6">
          <Panel>
            <div className="grid gap-4 text-sm md:grid-cols-5">
              <div><p className="text-xs text-muted-foreground">Application</p><p className="font-semibold">{a.id}</p></div>
              <div className="md:col-span-2"><p className="text-xs text-muted-foreground">Institution</p><p className="font-semibold">{a.institutionName || "—"} <span className="font-normal text-muted-foreground">({a.institutionId || "no ID"})</span></p></div>
              <div><p className="text-xs text-muted-foreground">Submitted</p><p className="font-semibold">{fmtDate(a.submittedAt)}</p></div>
              <div><p className="text-xs text-muted-foreground">Overall</p><StatusBadge status={overallStatus(a, findings)} /></div>
            </div>
            <p className="mt-4 text-xs text-muted-foreground">Report generated {fmtDateTime(new Date().toISOString())} · {findings.length} finding(s) · High {findings.filter((f) => f.severity === "High").length} · Medium {findings.filter((f) => f.severity === "Medium").length} · Low {findings.filter((f) => f.severity === "Low").length}</p>
          </Panel>
          <Panel title="Findings">
            {findings.length === 0 ? <p className="text-sm text-success">No discrepancies detected by the current rule set. Reviewer may proceed to standard approval checks.</p> : (
              <div className="space-y-4">{findings.map((f) => <FindingCard key={f.id} appId={a.id} f={f} status={a.findingStatuses[f.id] ?? "Open"} />)}</div>
            )}
          </Panel>
          <Panel title="Audit history">
            {a.audit.length === 0 ? <p className="text-sm text-muted-foreground">No actions recorded.</p> : (
              <ol className="space-y-2 text-sm">
                {[...a.audit].reverse().map((e) => (
                  <li key={e.id} className="flex gap-3 border-l-2 border-sidebar-primary pl-3">
                    <span className="w-40 shrink-0 text-xs text-muted-foreground">{fmtDateTime(e.at)}</span>
                    <span><strong>{e.actor}</strong> — {e.action}{e.findingId && <> · <code className="text-xs">{e.findingId}</code>: {e.from} → {e.to}</>}{e.note && <span className="text-muted-foreground"> · “{e.note}”</span>}</span>
                  </li>
                ))}
              </ol>
            )}
          </Panel>
        </div>
      )}
    </div>
  );
}

function FindingCard({ appId, f, status }: { appId: string; f: Finding; status: FindingStatus }) {
  const [next, setNext] = useState<FindingStatus>(status);
  const [note, setNote] = useState("");
  const save = () => {
    if (next === status && !note) { toast.info("No change to save."); return; }
    if ((next === "Resolved" || next === "Escalated") && !note.trim()) { toast.error(`Add a note explaining why the finding is ${next.toLowerCase()}.`); return; }
    try {
      setFindingStatus(appId, f.id, next, note.trim());
      setNote("");
      toast.success(`Finding marked ${next}`);
    } catch (e) {
      toast.error((e as Error).message);
    }
  };
  return (
    <div className="rounded-lg border p-4">
      <div className="flex flex-wrap items-center gap-2">
        <StatusBadge status={f.severity} />
        <span className="text-xs text-muted-foreground">{f.ruleId}</span>
        <span className="font-semibold">{f.ruleName}</span>
        <span className="text-sm text-muted-foreground">· {f.target}</span>
        <span className="ml-auto"><StatusBadge status={status} /></span>
      </div>
      <p className="mt-2 text-sm">{f.message}</p>
      {(f.expected || f.actual) && (
        <div className="mt-3 grid gap-2 rounded-md bg-muted p-3 text-xs md:grid-cols-2">
          <div><span className="text-muted-foreground">Expected / reference: </span><span className="font-medium">{f.expected}</span></div>
          <div><span className="text-muted-foreground">Found in application: </span><span className="font-medium">{f.actual}</span></div>
        </div>
      )}
      <p className="mt-2 text-sm"><span className="font-medium text-accent-foreground">Recommended action:</span> {f.recommendation}</p>
      <div className="mt-3 flex flex-wrap items-start gap-2">
        <select aria-label="Review status" className="h-9 rounded-md border border-input bg-background px-2 text-sm" value={next} onChange={(e) => setNext(e.target.value as FindingStatus)}>
          {FINDING_STATUSES.map((x) => <option key={x}>{x}</option>)}
        </select>
        <Textarea placeholder="Reviewer note (required for Resolved / Escalated)" value={note} onChange={(e) => setNote(e.target.value)} className="min-h-9 flex-1" rows={1} />
        <Button onClick={save}>Save decision</Button>
      </div>
    </div>
  );
}
